import io
import re
import zipfile
import yaml

# Standard Vale rule template generators

def _parse_substitutions(items: list[dict]) -> dict[str, str]:
    """
    Parses terminology rules looking for patterns like:
    - "Use 'X' instead of 'Y'"
    - "Say 'X', not 'Y'"
    - "Write 'X' rather than 'Y'"
    - "Replace 'Y' with 'X'"
    """
    swaps: dict[str, str] = {}
    patterns = [
        (r"(?:use|write|prefer)\s+(.+?)\s+(?:instead of|rather than)\s+(.+?)(?:\.|$)", False),
        (r"(?:say|use)\s+(.+?),\s*not\s+(.+?)(?:\.|$)", False),
        (r"replace\s+(.+?)\s+with\s+(.+?)(?:\.|$)", True),
    ]

    for item in items:
        if item.get("category") not in ("terminology", "tone"):
            continue
        content = item.get("content", "").strip()
        for pat, is_replace in patterns:
            match = re.search(pat, content, re.IGNORECASE)
            if match:
                p1 = match.group(1).strip().strip("'\"").strip()
                p2 = match.group(2).strip().strip("'\"").strip()
                if is_replace:
                    bad, good = p1.lower(), p2
                else:
                    good, bad = p1, p2.lower()
                if bad and good and bad != good.lower():
                    swaps[bad] = good
                break

    return swaps


def _parse_forbidden_tokens(items: list[dict]) -> list[str]:
    """
    Extracts banned or discouraged words/phrases from tone and promotional claims rules.
    """
    banned: set[str] = set()
    patterns = [
        r"(?:never|do not|don't|avoid)\s+(?:use|using|say|saying|mention|mentioning|write|writing)?\s*['\"]?([^'\"\n.]+?)['\"]?(?:\s+(?:in|for|on)|\.|$)",
        r"(?:forbidden|prohibited|banned)\s*(?:word|term|phrase)?s?:\s*['\"]?([^'\"\n.]+?)['\"]?(?:\.|$)",
    ]

    for item in items:
        content = item.get("content", "")
        for pattern in patterns:
            for match in re.finditer(pattern, content, re.IGNORECASE):
                phrase = match.group(1).strip().strip("'\"").strip().lower()
                if 2 <= len(phrase) <= 40:
                    banned.add(phrase)

    return sorted(banned)


def generate_vale_files(items: list[dict], brand_name: str = "CaraxesBrand") -> dict[str, str]:
    """
    Converts approved knowledge items into Vale style YAML files and .vale.ini.
    Returns a mapping from relative path to file content string.
    """
    files: dict[str, str] = {}

    # 1. Root .vale.ini configuration
    files[".vale.ini"] = f"""# Vale configuration generated by Caraxes Brand Governance
StylesPath = styles
MinAlertLevel = suggestion

[*.{{md,txt,html,rst}}]
BasedOnStyles = {brand_name}
"""

    style_dir = f"styles/{brand_name}"

    # 2. Terminology substitutions rule
    swaps = _parse_substitutions(items)
    if swaps:
        term_rule = {
            "extends": "substitution",
            "message": "Use '%s' instead of '%s' according to brand terminology.",
            "level": "error",
            "scope": "text",
            "ignorecase": False,
            "swap": swaps,
        }
        files[f"{style_dir}/Terminology.yml"] = yaml.dump(term_rule, sort_keys=False)

    # 3. Forbidden tokens rule (banned claims or tone violations)
    banned = _parse_forbidden_tokens(items)
    if banned:
        exist_rule = {
            "extends": "existence",
            "message": "'%s' violates brand guidelines. Avoid this phrase in public copy.",
            "level": "warning",
            "scope": "text",
            "ignorecase": True,
            "tokens": banned,
        }
        files[f"{style_dir}/BannedTerms.yml"] = yaml.dump(exist_rule, sort_keys=False)

    # 4. Exclamation limits rule (if any rule mentions exclamation marks)
    max_excl = 1
    found_excl_rule = False
    for item in items:
        if "exclamation" in item.get("content", "").lower():
            found_excl_rule = True
            m = re.search(r"(\d+)", item.get("content", ""))
            if m:
                max_excl = int(m.group(1))
            break

    if found_excl_rule:
        excl_rule = {
            "extends": "occurrence",
            "message": f"Too many exclamation marks. Brand guideline allows at most {max_excl}.",
            "level": "warning",
            "scope": "text",
            "max": max_excl,
            "token": "!",
        }
        files[f"{style_dir}/Exclamations.yml"] = yaml.dump(excl_rule, sort_keys=False)

    # 5. All-caps sentence rule
    files[f"{style_dir}/AllCaps.yml"] = yaml.dump(
        {
            "extends": "existence",
            "message": "Avoid writing whole sentences in ALL CAPS.",
            "level": "warning",
            "scope": "sentence",
            "raw": [r"\b[A-Z]{4,}(?:\s+[A-Z]{2,}){2,}\b"],
        },
        sort_keys=False,
    )

    return files


def build_vale_zip(items: list[dict], brand_name: str = "CaraxesBrand") -> bytes:
    """Creates a downloadable .zip archive containing .vale.ini and all style YAML rules."""
    files = generate_vale_files(items, brand_name)
    buf = io.BytesIO()

    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for path, content in files.items():
            zf.writestr(path, content)

    return buf.getvalue()
